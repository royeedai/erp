test('滚动时固定列和主体不错行：边滚边点，点到的就是看到的那一行', async ({ page }) => {
  await open(page)
  const body = page.locator('.vxe-table--main-wrapper .vxe-table--body-inner-wrapper')
  await body.hover()
  let worst = 0
  for (let i = 0; i < 24; i++) {
    await page.mouse.wheel(0, i % 2 ? 140 : 90)
    // 不等稳定，直接量同一行在左固定列、主体、右固定列的纵坐标
    const gap = await page.evaluate(() => {
      const ys = new Map<string, number[]>()
      for (const tr of document.querySelectorAll<HTMLElement>('.vxe-body--row[rowid]')) {
        const r = tr.getBoundingClientRect()
        if (r.width === 0) continue
        const id = tr.getAttribute('rowid')!
        ys.set(id, [...(ys.get(id) ?? []), r.y])
      }
      return Math.max(0, ...[...ys.values()].map((l) => Math.max(...l) - Math.min(...l)))
    })
    worst = Math.max(worst, gap)
  }
  expect(worst, '同一行在各表里的纵坐标差').toBeLessThanOrEqual(1)
})

test('录入对话框：必填、字段错误、冲突、保存新增、没填过直接走', async ({ page }) => {
  await login(page, 'admin', PATH)
  await expect(seen(page, '还没有查询')).toHaveCount(1)
  const start = async () => {
    await overlayGone(page)
    await page.getByRole('button', { name: '新增' }).click()
    await page.getByRole('menuitem', { name: '自制' }).click()
  }
  await start()
  const d = dialog(page, '自制')
  const code = d.locator('input[name="sample-code"]')
  const name = d.locator('input[name="sample-name"]')
  await expect(d.locator('.el-dialog__footer .el-button')).toHaveText(['保存', '保存新增', '取消'])
  await d.getByRole('button', { name: '取消' }).click()
  await expect(page.locator('.el-message-box').filter({ visible: true })).toHaveCount(0)
  await start()
  await name.fill('甲')
  await d.getByRole('button', { name: '保存', exact: true }).click()
  await expect(d).toContainText('请填写编码')
  await expect(code).toBeFocused()
  await expect(page.locator('.app-tab-dirty')).toHaveCount(1)
  await code.fill('DUP')
  await d.getByRole('button', { name: '保存', exact: true }).click()
  await expect(d).toContainText('编码已被占用')
  await expect(code).toBeFocused()
  await code.fill('BUSY')
  await expect(d).not.toContainText('编码已被占用')
  await d.getByRole('button', { name: '保存', exact: true }).click()
  const c = dialog(page, '数据已被他人修改')
  await expect(c).toContainText('你的值：甲')
  await expect(c).toContainText('最新值：同事改的')
  await c.getByRole('button', { name: '改用最新值' }).click()
  await expect(name).toHaveValue('同事改的')
  await expect(c).toBeHidden()
  await name.fill('还是我的')
  await d.getByRole('button', { name: '保存新增' }).click()
  await toastText(page, '已保存')
  await expect(code).toHaveValue('')
  await expect(code).toBeFocused()
  await code.fill('X')
  await d.getByRole('button', { name: '取消' }).click()
  await box(page).getByRole('button', { name: '继续填写' }).click()
  await expect(code).toHaveValue('X')
  await d.getByRole('button', { name: '取消' }).click()
  await box(page).getByRole('button', { name: '放弃修改' }).click()
  await expect(d).toBeHidden()
  await expect(page.locator('.app-tab-dirty')).toHaveCount(0)
})
